#!/bin/sh
# Selective sync with the tanxinhao line (user rule, 2026-10-12): sync only what is better, never merge everything.
# 1) Ledger/canon (world.json, proposals/, rules/, chronicle/, engine/) still follows upstream: one history.
# 2) Everything else (docs/living, viewers, tools) is NOT merged. New upstream commits are listed in
#    UPSTREAM_CANDIDATES.md for review; only ones judged better than ours get cherry-picked by hand.
set -e
git fetch -q upstream
LEDGER="proposals rules chronicle engine data i18n"   # world.json is generated by build_all, not tracked
git checkout upstream/main -- $LEDGER
if ! git diff --cached --quiet; then git commit -q -m "sync ledger from upstream $(git rev-parse --short upstream/main) ——Hark（刘线）"; fi
LAST=$(cat .upstream_reviewed 2>/dev/null || git merge-base HEAD upstream/main)
{
  echo "# 上游候选（待评估，只挑更好的手动 cherry-pick）"
  echo "已审阅到：$LAST"
  git log --reverse --format='- %h %s' "$LAST..upstream/main" -- . ':(exclude)proposals' ':(exclude)rules' ':(exclude)chronicle' ':(exclude)engine' ':(exclude)data' ':(exclude)i18n'
} > UPSTREAM_CANDIDATES.md
python3 engine/build_all.py >/dev/null && python3 engine/check.py
